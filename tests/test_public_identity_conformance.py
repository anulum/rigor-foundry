# RigorFoundry — Public identity conformance tests
"""Exercise technical-format admission and attribution refusal through the API."""

from __future__ import annotations

import pytest

from tools.check_public_identity import public_identity_errors

_NAME = "Clau" + "de"
_FORMAT = _NAME + " JSONL"


@pytest.mark.parametrize(
    "text",
    [
        "",
        "Vendor-neutral source and fixture identities.",
        f"The selected {_FORMAT} format is supported.",
        f"Read the retained {_FORMAT} source.",
        f"Match a selected {_FORMAT} message to its pinned line.",
        f"The source format is a constrained {_FORMAT} subset.",
        f"Accept a constrained subset of retained\n{_FORMAT}.",
        f"The selected `{_FORMAT}` transcript is bounded.",
        f"The {_NAME.upper()}\r\nJSONL format is supported.",
        f"The {_FORMAT} source and {_FORMAT} message are selected.",
        f"Supported native parser\n\nThe {_FORMAT} source is selected.",
        f"The {_FORMAT} source is selected.\n\nIndependent signatures remain required.",
    ],
)
def test_technical_format_and_neutral_text_are_accepted(text: str) -> None:
    """Registered factual format names survive wrapping and repeated mentions."""
    assert public_identity_errors(text) == []


@pytest.mark.parametrize(
    "text",
    [
        _NAME,
        _FORMAT,
        f"The {_NAME} YAML format is supported.",
        f"The {_FORMAT}-agent source is selected.",
        f"The {_FORMAT}/seat source is selected.",
        f"The {_FORMAT}@session source is selected.",
        f"The PROJECT/{_FORMAT} source is selected.",
        f"The {_FORMAT} source was generated by {_NAME}.",
        f"Generated by {_FORMAT}; source format.",
        f"Generated\nby {_FORMAT}; source format.",
        f"Generated by\n\n{_FORMAT} source format.",
        f"Author:\n\n{_FORMAT} source format.",
        f'Agent = "\n\n{_FORMAT} source format.',
        f"Author: {_FORMAT}; source format.",
        f"Seat: {_FORMAT}; source format.",
        f"Agent {_FORMAT}; source format.",
        f"Reviewer {_FORMAT}; source format.",
        f"Contributor {_FORMAT}; source format.",
        f"Powered by {_FORMAT}; source format.",
        f"Built with {_FORMAT}; source format.",
        f"Written using {_FORMAT}; source format.",
        f"© {_FORMAT}; source format.",
        f"The {_FORMAT} source is selected.\n\nAuthor: {_NAME}",
        f"The {_FORMAT} source is selected; {_NAME} is also mentioned.",
        f"The {_FORMAT} source is selected; Open" + "AI authored this.",
    ],
)
def test_format_name_cannot_hide_identity_or_attribution(text: str) -> None:
    """Technical words never waive actor labels, attribution or other occurrences."""
    assert public_identity_errors(text)


@pytest.mark.parametrize(
    "identity",
    ["Co" + "dex", "Open" + "AI", "Chat" + "GPT", "Anthro" + "pic", "Gr" + "ok", "x" + "AI"],
)
def test_unregistered_names_still_require_review(identity: str) -> None:
    """Other identity names receive no exception from an adjacent format name."""
    assert public_identity_errors(f"The {_FORMAT} source is selected.\n\n{identity}") == [
        "vendor identity is public"
    ]


def test_each_disallowed_identity_is_reported_once_across_paragraphs() -> None:
    """Repeated uses retain one diagnostic per identity without losing a second actor."""
    second = "Co" + "dex"
    assert public_identity_errors(f"{_NAME}\n\n{_NAME}\n\n{second}") == [
        "vendor identity is public",
        "vendor identity is public",
    ]

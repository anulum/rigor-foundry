# RigorFoundry — strict Yarn 1 lockfile syntax witnesses
"""Witness the strict Yarn 1 reader on yarn 1.22.22's own output and on every refused shape."""

from __future__ import annotations

from pathlib import Path

import pytest
from lockfile_repository_support import fixture_text

from rigor_foundry.lockfile_model import LockfileRefusal
from rigor_foundry.lockfile_yarn1_syntax import parse_yarn1

YARN1 = (
    Path(__file__).resolve().parent / "fixtures" / "lockfiles" / "yarn-1.22.22-v1" / "yarn.lock.gz"
)
HEADER = (
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"
)
ENTRY = 'ms@2.1.2:\n  version "2.1.2"\n  dependencies:\n    "@scope/dep" "^1.0.0"\n'


def test_the_real_yarn_output_reads_entry_by_entry() -> None:
    """Yarn 1.22.22's lockfile reads completely: specifiers, lines, fields and blocks."""
    entries = parse_yarn1(fixture_text(YARN1))
    assert len(entries) == 60
    first = entries[0]
    assert (first.specifiers, first.line) == (("ansi-regex@^2.0.0",), 5)
    assert first.fields["integrity"].startswith("sha512-")
    grouped = next(entry for entry in entries if len(entry.specifiers) > 1)
    assert grouped.specifiers == ("lodash.assign@^4.0.3", "lodash.assign@^4.0.6")
    debug = next(entry for entry in entries if entry.specifiers == ("debug@4.3.4",))
    assert debug.blocks == ("dependencies",)
    quoted = next(
        entry for entry in entries if entry.specifiers[0].startswith("is-number@github:")
    )
    assert quoted.fields["version"] == "7.0.0"


def test_an_all_crlf_file_reads_as_lf_and_an_empty_body_has_no_entries() -> None:
    """Windows checkouts with ``autocrlf`` give the same entries; a header alone is no entry."""
    text = HEADER + ENTRY
    assert parse_yarn1(text.replace("\n", "\r\n")) == parse_yarn1(text)
    assert parse_yarn1(HEADER) == ()
    assert parse_yarn1(HEADER + ENTRY.rstrip("\n"))[0].fields == {"version": "2.1.2"}


def test_quoted_and_bare_spellings_of_one_specifier_are_one_specifier() -> None:
    """Specifiers compare unquoted, so a quoted repeat is a conflict.

    One version resolved under two different specifiers is normal and reads as two entries.
    """
    same_version = HEADER + 'a@^1.0.0:\n  version "1.0.0"\n\na@~1.0.0:\n  version "1.0.0"\n'
    assert len(parse_yarn1(same_version)) == 2
    with pytest.raises(LockfileRefusal) as refused:
        parse_yarn1(HEADER + 'a@^1.0.0:\n  version "1.0.0"\n\n"a@^1.0.0":\n  version "1.0.0"\n')
    assert refused.value.reason == "conflicting-entries"


@pytest.mark.parametrize(
    ("text", "reason"),
    [
        (HEADER + 'a@1, a@1:\n  version "1"\n', "conflicting-entries"),
        (HEADER + 'a@1:\n  version "1"\n  version "2"\n', "conflicting-entries"),
        (HEADER + "a@1:\n  dependencies:\n  dependencies:\n", "conflicting-entries"),
        (HEADER + 'a@1:\n  dependencies:\n    b "1"\n    b "2"\n', "conflicting-entries"),
        (HEADER.replace("\n", "\r\n") + ENTRY, "unparseable"),
        (HEADER + 'a@1:\r  version "1"\n', "unparseable"),
        ("\ufeff" + HEADER + ENTRY, "unparseable"),
        ("# yarn lockfile v2\n\n" + ENTRY, "unparseable"),
        (ENTRY, "unparseable"),
        (HEADER + ENTRY + "\n# trailing comment\n", "unparseable"),
        (HEADER + ENTRY + "\n#note:\n", "unparseable"),
        (HEADER + 'a@1\n  version "1"\n', "unparseable"),
        (HEADER + '  version "1"\n', "unparseable"),
        (HEADER + 'a@1:\n\tversion "1"\n', "unparseable"),
        (HEADER + 'a@1:\n   version "1"\n', "unparseable"),
        (HEADER + 'a@1:\n  version "1"\n    b "1"\n', "unparseable"),
        (HEADER + "a@1:\n  dependencies:\n    b:\n", "unparseable"),
        (HEADER + 'a@1:\n  version "1" extra\n', "unparseable"),
        (HEADER + 'a@1:\n  "version\n', "unparseable"),
        (HEADER + 'a@1:\n  version "bad \\q"\n', "unparseable"),
        (HEADER + "a@1:\n  version 1:\n", "unparseable"),
        (HEADER + 'a@1, :\n  version "1"\n', "unparseable"),
        (HEADER + ':\n  version "1"\n', "unparseable"),
        (HEADER + 'a@1,b@1:\n  version "1"\n', "unparseable"),
        (HEADER + '"a@1" junk:\n  version "1"\n', "unparseable"),
        (HEADER + 'a:b@1:\n  version "1"\n', "unparseable"),
        (HEADER + '"bad \\q"@1:\n  version "1"\n', "unparseable"),
    ],
)
def test_every_other_shape_is_refused_by_name(text: str, reason: str) -> None:
    """Anything Yarn 1 does not write is refused, never skipped, and repeats are conflicts.

    Parameters
    ----------
    text : str
        The refused text.
    reason : str
        The expected refusal reason.
    """
    with pytest.raises(LockfileRefusal) as refused:
        parse_yarn1(text)
    assert refused.value.reason == reason

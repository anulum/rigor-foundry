# RigorFoundry — lockfile kind detection witnesses
"""Witness lockfile kind detection, including the Yarn 1 and Yarn 2+ split of ``yarn.lock``."""

from __future__ import annotations

import pytest

from rigor_foundry.lockfile_kinds import is_lockfile_path, lockfile_kind
from rigor_foundry.lockfile_model import LockfileRefusal

YARN_V1 = (
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n"
    "# yarn lockfile v1\n"
    "\n"
    "\n"
    'left-pad@^1.3.0:\n  version "1.3.0"\n'
)
YARN_BERRY = (
    '# This file is generated by running "yarn install" inside your project.\n'
    "# Manual changes might be lost - proceed with caution!\n"
    "\n"
    "__metadata:\n  version: 8\n  cacheKey: 10c0\n"
)


@pytest.mark.parametrize(
    ("path", "kind"),
    [
        ("package-lock.json", "npm"),
        ("web/npm-shrinkwrap.json", "npm"),
        ("pnpm-lock.yaml", "pnpm"),
        ("web/pnpm-lock.feature!login.yaml", "pnpm"),
        ("crates/tool/Cargo.lock", "cargo"),
        ("go.sum", "go"),
        ("poetry.lock", "poetry"),
        ("services/api/Pipfile.lock", "pipenv"),
    ],
)
def test_a_lockfile_kind_follows_its_exact_file_name(path: str, kind: str) -> None:
    """Each kind other than Yarn is named by its exact file name, in any directory.

    Parameters
    ----------
    path : str
        A repository-relative POSIX path.
    kind : str
        The expected kind.
    """
    assert is_lockfile_path(path)
    assert lockfile_kind(path, "") == kind


@pytest.mark.parametrize(
    "path",
    [
        "Package-Lock.json",
        "package-lock.json.bak",
        "yarn.lock.orig",
        "go.mod",
        "Pipfile",
        "lock",
        "pnpm-lock.yml",
        "pnpm-lock..yaml",
    ],
)
def test_other_paths_are_not_lockfiles(path: str) -> None:
    """Names are compared exactly, so near misses and manifests are not lockfiles.

    Parameters
    ----------
    path : str
        A path that is not a lockfile.
    """
    assert not is_lockfile_path(path)
    with pytest.raises(ValueError, match="not a lockfile path"):
        lockfile_kind(path, "")


def test_a_yarn_lock_with_the_v1_header_is_yarn_1() -> None:
    """The ``# yarn lockfile v1`` header in the leading comments selects Yarn 1."""
    assert is_lockfile_path("yarn.lock")
    assert lockfile_kind("packages/app/yarn.lock", YARN_V1) == "yarn-v1"


def test_a_yarn_lock_with_a_metadata_block_is_yarn_berry() -> None:
    """A top-level ``__metadata:`` block selects Yarn 2 and later."""
    assert lockfile_kind("yarn.lock", YARN_BERRY) == "yarn-berry"


@pytest.mark.parametrize(
    ("text", "reason"),
    [
        ("", "an empty file shows neither form"),
        ('left-pad@^1.3.0:\n  version "1.3.0"\n', "no header and no metadata block"),
        (YARN_V1 + "\n__metadata:\n  version: 8\n", "both forms at once"),
        ('left-pad@^1.3.0:\n  version "1.3.0"\n# yarn lockfile v1\n', "a header after content"),
        ("# yarn lockfile v1 \n", "a header with trailing text"),
        ('"__metadata":\n  version: 8\n', "a quoted metadata key Yarn does not write"),
        ("  __metadata:\n    version: 8\n", "an indented metadata key"),
    ],
)
def test_a_yarn_lock_with_neither_or_both_forms_is_refused(text: str, reason: str) -> None:
    """A ``yarn.lock`` that shows neither form, or both, is refused as ambiguous.

    Parameters
    ----------
    text : str
        The file text.
    reason : str
        Why the text is ambiguous, for the failure message.
    """
    with pytest.raises(LockfileRefusal) as refused:
        lockfile_kind("yarn.lock", text)
    assert refused.value.reason == "ambiguous-yarn-lock", reason


def test_a_yarn_lock_with_a_byte_order_mark_is_unparseable() -> None:
    """A byte-order mark is no Yarn form at all, so the file is unparseable, not ambiguous."""
    with pytest.raises(LockfileRefusal) as refused:
        lockfile_kind("yarn.lock", "\ufeff" + YARN_V1)
    assert refused.value.reason == "unparseable"

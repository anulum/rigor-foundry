/**
 * Build real adopter evidence from complete copied production and original test files.
 * Retain command streams, source byte identities, and actual CLI report and draft-ledger artifacts.
 * @module
 */

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { cp, mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { CommandExecutionFailure, runCli } from "../../src/cli.js";
import { parseAuditReport, parseReviewDocument } from "../../src/contracts.js";
import type { AuditReport, ReviewDocument } from "../../src/contracts.js";

/** Byte identity of one complete production or original test file copied into a fixture. */
export interface ProductionSourcePin {
  /** Repository-relative path retained unchanged in the copied worktree. */
  readonly path: string;
  /** Number of bytes read from both the source and its verified copy. */
  readonly bytes: number;
  /** Lowercase SHA-256 of the exact copied bytes. */
  readonly sha256: string;
}

/** Real Git worktree and CLI-produced evidence shared by native owner tests. */
export interface EvidenceRepository {
  /** Owned temporary Git worktree; setup failures retain it for diagnosis. */
  readonly root: string;
  /** Retained command streams, source pins, and evidence under the owned build output. */
  readonly artifactRoot: string;
  /** Absolute report path generated by the real scan command. */
  readonly reportPath: string;
  /** Absolute ledger path generated by the real review-template command. */
  readonly reviewPath: string;
  /** Explicit adopter policy, deliberately outside the scanner's default discovery names. */
  readonly policyPath: string;
  /** Actual report from default discovery when the standard policy names are absent. */
  readonly treeReport: AuditReport;
  /** Real template ledger bound to the missing-policy repository-tree report. */
  readonly treeReviews: ReviewDocument;
  /** Parsed production report, with identities computed by the actual CLI. */
  readonly report: AuditReport;
  /** Parsed production ledger cross-bound to that report. */
  readonly reviews: ReviewDocument;
  /** Verifiable byte identities of the complete copied production and test files. */
  readonly sourcePins: readonly ProductionSourcePin[];
}

/**
 * Build evidence using complete current source files and actual Git and RigorFoundry commands.
 *
 * The fixture is a two-file adopter repository, not a claim that all of RigorFoundry was scanned.
 * Its explicit 500-line source ceiling is stricter than bootstrap's default and yields a real
 * oversized-module observation from the copied inventory owner, without inserting toy code.
 * @returns The owned repository, CLI-generated documents, and exact copied-source identities.
 * @throws {Error} If a real setup command, source-copy check, or evidence contract fails.
 */
export async function createEvidenceRepository(): Promise<EvidenceRepository> {
  const sourceRoot =
    process.env["RIGOR_FOUNDRY_SOURCE_ROOT"] ?? path.resolve(__dirname, "../../../../..");
  const cli = process.env["RIGOR_FOUNDRY_CLI"] ?? "rigor";
  const root = await mkdtemp(path.join(tmpdir(), "rigor-native-evidence-"));
  const evidence = path.join(root, ".rigor");
  await mkdir(path.join(root, "src", "rigor_foundry"), { recursive: true });
  await mkdir(path.join(root, "tests"));
  await mkdir(evidence);
  await writeFile(path.join(root, ".gitignore"), ".rigor/\n", "utf8");
  const sourcePins: ProductionSourcePin[] = [];
  for (const name of ["src/rigor_foundry/git_inventory.py", "tests/test_git_inventory.py"]) {
    const source = await readFile(path.join(sourceRoot, name));
    const target = path.join(root, name);
    await writeFile(target, source);
    assert.deepEqual(await readFile(target), source, `production source copy changed: ${name}`);
    sourcePins.push({
      path: name,
      bytes: source.length,
      sha256: createHash("sha256").update(source).digest("hex"),
    });
  }
  await writeFile(
    path.join(evidence, "production-source-pins.json"),
    `${JSON.stringify(
      {
        sourceRoot,
        sourcePins,
      },
      null,
      2,
    )}\n`,
    "utf8",
  );

  let sequence = 0;
  /**
   * Execute a real setup command and preserve its bounded streams on success or failure.
   * @param executable - Actual Git or RigorFoundry executable, without a shell.
   * @param args - Literal arguments applied only to this owned adopter worktree.
   * @returns Completion after the real process closes with zero status.
   */
  const execute = async (executable: string, args: readonly string[]): Promise<void> => {
    sequence += 1;
    const stem = path.join(evidence, `command-${String(sequence)}`);
    await writeFile(`${stem}.argv.json`, `${JSON.stringify({ executable, args })}\n`, "utf8");
    try {
      const result = await runCli(executable, args, { cwd: root, timeoutMilliseconds: 60_000 });
      await writeFile(`${stem}.stdout`, result.stdout, "utf8");
      await writeFile(`${stem}.stderr`, result.stderr, "utf8");
    } catch (error: unknown) {
      try {
        if (error instanceof CommandExecutionFailure) {
          await writeFile(`${stem}.stdout`, error.output.stdout, "utf8");
          await writeFile(`${stem}.stderr`, error.output.stderr, "utf8");
        }
        await writeFile(
          `${stem}.failure.json`,
          JSON.stringify({
            fixtureRoot: root,
            executable,
            args,
            commandTrace: stem,
            capturedOutput: error instanceof CommandExecutionFailure,
          }) + "\n",
          "utf8",
        );
      } catch (preservationError: unknown) {
        process.stderr.write(
          `RigorFoundry fixture trace write failed at ${stem}: ${String(preservationError)}\n`,
        );
      }
      process.stderr.write(
        `RigorFoundry native fixture failure at ${root}; command trace ${stem}\n`,
      );
      throw error;
    }
  };

  await execute("git", ["init", "--initial-branch=main"]);
  await execute("git", ["config", "user.name", "RigorFoundry Native Tests"]);
  await execute("git", ["config", "user.email", "native-tests@example.invalid"]);
  await execute("git", ["config", "commit.gpgsign", "false"]);
  await execute(cli, [
    "bootstrap",
    "--root",
    ".",
    "--policy",
    "native-evidence-policy.json",
    "--todo",
    ".rigor/TODO.md",
    "--review-ledger",
    ".rigor/reviews.json",
    "--source-root",
    "src",
    "--test-root",
    "tests",
    "--source-line-threshold",
    "500",
  ]);
  await execute("git", ["add", ".gitignore", "native-evidence-policy.json", "src", "tests"]);
  await execute("git", [
    "commit",
    "-m",
    "test: capture complete production owner for native evidence",
  ]);
  await execute(cli, [
    "scan",
    "--root",
    ".",
    "--policy",
    "native-evidence-policy.json",
    "--json-out",
    ".rigor/report.json",
  ]);
  await execute(cli, [
    "review-template",
    "--report",
    ".rigor/report.json",
    "--output",
    ".rigor/reviews.json",
  ]);
  await execute(cli, [
    "validate-review",
    "--report",
    ".rigor/report.json",
    "--review",
    ".rigor/reviews.json",
  ]);
  await execute(cli, ["scan", "--root", ".", "--json-out", ".rigor/tree-report.json"]);
  await execute(cli, [
    "review-template",
    "--report",
    ".rigor/tree-report.json",
    "--output",
    ".rigor/tree-reviews.json",
  ]);
  await execute(cli, [
    "validate-review",
    "--report",
    ".rigor/tree-report.json",
    "--review",
    ".rigor/tree-reviews.json",
  ]);

  const reportPath = path.join(evidence, "report.json");
  const reviewPath = path.join(evidence, "reviews.json");
  const artifactRoot = path.resolve(__dirname, "../..", "fixtures", path.basename(root));
  await cp(evidence, artifactRoot, { recursive: true, errorOnExist: true, force: false });
  for (const pin of sourcePins) {
    const destination = path.join(artifactRoot, "production", pin.path);
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, await readFile(path.join(root, pin.path)));
  }
  const report = parseAuditReport(JSON.parse(await readFile(reportPath, "utf8")) as unknown);
  const reviews = parseReviewDocument(
    JSON.parse(await readFile(reviewPath, "utf8")) as unknown,
    report,
  );
  const treeReport = parseAuditReport(
    JSON.parse(await readFile(path.join(evidence, "tree-report.json"), "utf8")) as unknown,
  );
  const treeReviews = parseReviewDocument(
    JSON.parse(await readFile(path.join(evidence, "tree-reviews.json"), "utf8")) as unknown,
    treeReport,
  );
  assert.ok(report.candidates.some((candidate) => candidate.anchor.kind === "tracked-blob"));
  assert.ok(
    treeReport.candidates.some((candidate) => candidate.anchor.kind === "repository-tree"),
  );
  assert.equal(reviews.reviews.length, report.candidates.length);
  return {
    root,
    artifactRoot,
    reportPath,
    reviewPath,
    policyPath: path.join(root, "native-evidence-policy.json"),
    treeReport,
    treeReviews,
    report,
    reviews,
    sourcePins,
  };
}

/** Files coordinating a genuine CLI completion with an explicitly bounded POSIX test process. */
export interface ValidationBarrier {
  /** Owned executable that delegates unchanged arguments to the actual canonical CLI. */
  readonly executable: string;
  /** Published only after the real CLI has exited successfully. */
  readonly readyPath: string;
  /** Test-created release signal allowing that successful process to finish. */
  readonly releasePath: string;
  /** Actual CLI arguments, streams, status and input hashes captured by the delegating process. */
  readonly tracePath: string;
}

/**
 * Create an owned POSIX executable that pauses after genuine canonical validation succeeds.
 * @param root - Owned adopter whose ignored evidence directory holds the barrier files.
 * @param cli - Actual canonical CLI executed unchanged without a shell.
 * @returns Exclusive barrier paths; the caller releases the child in its cleanup path.
 */
export async function createPosixValidationBarrier(
  root: string,
  cli: string,
): Promise<ValidationBarrier> {
  if (process.platform === "win32") {
    const { createWindowsValidationBarrier } = await import("./windowsValidationBarrier.js");
    return await createWindowsValidationBarrier(root, cli);
  }
  const directory = await mkdtemp(path.join(root, ".rigor", "validation-barrier-"));
  const executable = path.join(directory, "canonical-validation");
  const readyPath = path.join(directory, "ready");
  const releasePath = path.join(directory, "release");
  const tracePath = path.join(directory, "trace.json");
  const source = `#!/usr/bin/env node
const { spawnSync } = require("node:child_process");
const { createHash } = require("node:crypto");
const { existsSync, readFileSync, statSync, writeFileSync } = require("node:fs");
const path = require("node:path");
const args = process.argv.slice(2);
const result = spawnSync(${JSON.stringify(cli)}, args, {
  cwd: process.cwd(), shell: false, encoding: "utf8", timeout: 60000, maxBuffer: 1048576
});
process.stdout.write(result.stdout ?? "");
process.stderr.write(result.stderr ?? "");
if (result.error !== undefined) throw result.error;
const report = args[args.indexOf("--report") + 1];
const review = args[args.indexOf("--review") + 1];
writeFileSync(${JSON.stringify(tracePath)}, JSON.stringify({
  executable: ${JSON.stringify(cli)}, args, cwd: process.cwd(),
  nodeExecutable: process.execPath, nodeVersion: process.version,
  reportMode: statSync(report).mode & 0o777,
  reviewMode: statSync(review).mode & 0o777,
  directoryMode: statSync(path.dirname(report)).mode & 0o777,
  status: result.status, signal: result.signal,
  stdout: result.stdout, stderr: result.stderr,
  reportPath: report, reviewPath: review,
  reportSha256: createHash("sha256").update(readFileSync(report)).digest("hex"),
  reviewSha256: createHash("sha256").update(readFileSync(review)).digest("hex")
}) + "\\n", { flag: "wx", mode: 0o600 });
if (result.status !== 0) process.exit(result.status ?? 1);
writeFileSync(${JSON.stringify(readyPath)}, "validated\\n", { flag: "wx", mode: 0o600 });
const deadline = Date.now() + 15000;
const delay = new Int32Array(new SharedArrayBuffer(4));
while (!existsSync(${JSON.stringify(releasePath)})) {
  if (Date.now() >= deadline) process.exit(124);
  Atomics.wait(delay, 0, 0, 10);
}
process.exit(result.status);
`;
  await writeFile(executable, source, { flag: "wx", mode: 0o700 });
  return { executable, readyPath, releasePath, tracePath };
}

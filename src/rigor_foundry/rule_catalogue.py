def rule_guidance() -> Mapping[str, RuleGuidance]:
    """Return the fixed guidance of every registered rule, in rule-registry order.

    Returns
    -------
    Mapping[str, RuleGuidance]
        A read-only mapping with exactly one entry per ``RULES`` id.

    Raises
    ------
    KeyError
        If a registered rule has no published guidance. The rule-catalogue tests also
        refuse a rule published twice or a published id that is not registered.
    """
    published = {
        rule_id: guidance
        for owner in _GUIDANCE_OWNERS
        for rule_id, guidance in owner.RULE_GUIDANCE.items()
    }
    return MappingProxyType({rule.rule_id: published[rule.rule_id] for rule in RULES})


def rule_catalogue_anchor(rule_id: str) -> str:
    """Return the stable catalogue anchor of one rule heading.

    Parameters
    ----------
    rule_id : str
        A registered rule id.

    Returns
    -------
    str
        The heading slug that GitHub and the documentation site both derive from the id.
    """
    return rule_id.lower()


def render_rule_catalogue() -> str:
    """Render the generated rule catalogue page from the registry and its guidance.

    Returns
    -------
    str
        The exact Markdown text that ``docs/rule-catalogue.md`` must hold.
    """
    guidance = rule_guidance()
    lines = [
        "# Rule catalogue",
        "",
        "<!-- Generated by `python -m tools.render_rule_catalogue`; do not edit by hand. -->",
        "",
        f"This catalogue lists all {len(RULES)} registered rules, grouped by category, with the fixed",
        "rationale and verification guidance each detector attaches to its candidates. SARIF rule",
        "`helpUri` values point at these sections.",
        "",
        CANDIDATE_NOT_VERDICT,
    ]
    categories = list(dict.fromkeys(rule.category for rule in RULES))
    for category in categories:
        lines += ["", f"## {category}"]
        for rule in (item for item in RULES if item.category == category):
            entry = guidance[rule.rule_id]
            lines += [
                "",
                f"### {rule.rule_id}",
                "",
                rule.summary,
                "",
                f"Introduced in {rule.introduced}.",
            ]
            cases = entry.all_cases()
            for number, case in enumerate(cases, start=1):
                label = (
                    f" (case {number} of {len(cases)}: {case.condition})" if len(cases) > 1 else ""
                )
                lines += [
                    "",
                    f"**Why it matters{label}.** {case.rationale}",
                    "",
                    f"**How to verify{label}.** {case.verification}",
                ]
    return "\n".join(lines) + "\n"

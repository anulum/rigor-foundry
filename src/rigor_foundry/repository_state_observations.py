@dataclass(frozen=True)
class RepositoryStateObservation:
    """Actual before/current preimages and their derived independent state identity.

    This is not an owner-proof token or an atomic snapshot. Required host roots,
    source-access authority, generated lineage, retained runtime lifetimes and
    authenticated inventory/fact/task admission remain separate obligations.

    Attributes
    ----------
    state : RepositoryState1
        Independent identities derived from the complete observed preimages.
    inputs : ConfiguredInventoryInputs
        Every original current capture, index stage and path-ownership row.
    baseline : InventoryBaseline1
        Independently retained before-images, including earlier directory state.
    source_snapshot_digest : str
        Actual selected sources, baseline lifetime, state and directory objects.
    """

    state: RepositoryState1
    inputs: ConfiguredInventoryInputs
    baseline: InventoryBaseline1
    source_snapshot_digest: str


def capture_inventory_baseline(
    *,
    baseline_id: str,
    baselines: tuple[InventoryGitBaseline, ...],
    monorepo_root: Path,
    domain_source: RetainedContextSource,
    registry_source: RetainedContextSource,
    contract_source: RetainedContextSource,
    implementation: OwnerImplementationSnapshot,
    runner: GitRunner,
    budget: PolicyReadBudget1,
) -> InventoryBaseline1:
    """Capture every declared before-image through the actual configured collector.

    Parameters
    ----------
    baseline_id:
        Explicit identity for the resulting earlier-source record.
    baselines:
        Exact full commit for every and only declared Git root.
    monorepo_root:
        Already authorised physical root selected by enclosing host composition.
    domain_source, registry_source, contract_source:
        Actual held original configuration selections, not supplied parser data.
    implementation:
        Prior complete package/interpreter observation used by the collector.
    runner:
        Actual trusted Git runner under the enclosing host's policy.
    budget:
        Explicit unchanged capture and retained-data allocation ceilings.

    Returns
    -------
    InventoryBaseline1
        Actual Git before blobs and current directory preimages. Persist and
        independently select this record before later changes; calling capture
        again after a mutation does not recover the earlier directory state.
        Capturing generated bytes does not establish their generator lineage.

    Raises
    ------
    ValueError
        If selections, original preimages or explicit read limits disagree.
    RuntimeError
        If trusted Git execution or required descriptor primitives are unavailable.
    OSError
        If an actual configured source cannot be inspected safely.
    """
    identity = require_identifier(baseline_id, "inventory baseline identity")
    inputs = observe_configured_inventory_inputs(
        baselines=baselines,
        monorepo_root=monorepo_root,
        domain_source=domain_source,
        registry_source=registry_source,
        contract_source=contract_source,
        implementation=implementation,
        runner=runner,
        budget=budget,
    )
    domain = read_inventory_domain_selection(
        domain_source, registry_source, contract_source, implementation
    )
    roots: list[InventoryBaselineRoot] = []
    for item in inputs.roots:
        actual = item.inputs
        if isinstance(actual, RepositoryFileInputs):
            roots.append(
                InventoryBaselineRoot(
                    item.root, actual.git.baseline_head, actual.baseline_files, ()
                )
            )
        else:
            roots.append(InventoryBaselineRoot(item.root, None, actual.files, actual.directories))
    return InventoryBaseline1.build(
        baseline_id=identity,
        project_id=domain.project_id,
        domain_reference=inputs.domain_reference,
        registry_reference=inputs.registry_reference,
        roots=tuple(roots),
        budget=budget,
    )


def observe_repository_state(
    *,
    root_id: str,
    baseline_source: RetainedContextSource,
    monorepo_root: Path,
    domain_source: RetainedContextSource,
    registry_source: RetainedContextSource,
    contract_source: RetainedContextSource,
    implementation: OwnerImplementationSnapshot,
    runner: GitRunner,
    budget: PolicyReadBudget1,
) -> RepositoryStateObservation:
    """Derive state from every actual root and independently retained before-images.

    Parameters
    ----------
    root_id:
        Declared Git root whose commit/tree fields identify this state. Choosing
        it never filters other roots, their index stages, files or topology.
    baseline_source:
        Actual independently selected retained earlier baseline source.
    monorepo_root, domain_source, registry_source, contract_source:
        Already authorised host root and original borrowed source selections.
    implementation, runner, budget:
        Same complete implementation, actual Git and explicit read ceilings
        required by the complete configured collector.

    Returns
    -------
    RepositoryStateObservation
        Independently hashed baseline/index/worktree/untracked/generated/domain
        data and all original preimages. Unknown classifications, unsupported
        files, deleted before-images and every configured root remain bound.

    Raises
    ------
    ValueError
        If retained sources, configured roots or original Git before-images
        disagree. Domain/registry changes require explicit history reconciliation;
        they do not silently discard roots from the earlier baseline.
    RuntimeError
        If trusted Git or descriptor-based inspection refuses.
    OSError
        If retained or configured sources cannot be inspected safely.
    """
    selected = require_identifier(root_id, "repository state root")
    if type(baseline_source) is not RetainedContextSource or type(budget) is not PolicyReadBudget1:
        raise ValueError("actual retained baseline and policy read budget are required")
    limits = PolicyReadBudget1.from_dict(budget.to_dict())
    target = baseline_source.read()
    if type(target) is not InventoryBaseline1:
        raise ValueError("retained baseline source has the wrong owning kind")
    baseline = InventoryBaseline1.from_dict(target.to_dict(), budget=limits)
    baselines = tuple(
        InventoryGitBaseline(item.root.root_id, item.git_head)
        for item in baseline.roots
        if item.git_head is not None
    )
    inputs = observe_configured_inventory_inputs(
        baselines=baselines,
        monorepo_root=monorepo_root,
        domain_source=domain_source,
        registry_source=registry_source,
        contract_source=contract_source,
        implementation=implementation,
        runner=runner,
        budget=limits,
    )
    domain = read_inventory_domain_selection(
        domain_source, registry_source, contract_source, implementation
    )
    registry = cast(ProjectRegistry, registry_source.read())
    contract = cast(ContextProducerContract1, contract_source.read())
    reference = baseline_source.reference
    if (reference.kind, reference.format_version) not in contract.source_formats:
        raise ValueError("inventory contract excludes the selected baseline source format")
    if (
        baseline.project_id != domain.project_id
        or baseline.domain_reference != inputs.domain_reference
        or baseline.registry_reference != inputs.registry_reference
        or tuple(item.root for item in baseline.roots) != tuple(item.root for item in inputs.roots)
    ):
        raise ValueError("retained baseline differs from the complete current source selection")
    git_roots: list[dict[str, object]] = []
    directory_roots: list[dict[str, object]] = []
    generated_roots: list[dict[str, object]] = []
    directory_objects: list[dict[str, object]] = []
    index_rows: list[dict[str, object]] = []
    untracked_rows: list[dict[str, object]] = []
    current_rows: list[dict[str, object]] = []
    selected_inputs: RepositoryFileInputs | None = None
    for before, current in zip(baseline.roots, inputs.roots, strict=True):
        actual = current.inputs
        if isinstance(actual, RepositoryFileInputs):
            if before.files != actual.baseline_files:
                raise ValueError("retained Git baseline preimages differ from actual commit blobs")
            git = actual.git
            if current.root.root_id == selected:
                selected_inputs = actual
            git_roots.append(
                {
                    "root_id": current.root.root_id,
                    "baseline_head": git.baseline_head,
                    "baseline_tree": git.baseline_tree,
                    "head": git.head,
                    "head_tree": git.head_tree,
                    "object_format": git.object_format,
                    "git_provenance": git.git_provenance.to_dict(),
                    "status_bytes_hex": git.status_bytes.hex(),
                }
            )
            index_rows.append({"root_id": current.root.root_id, "index": git.index.to_dict()})
            untracked = frozenset(git.untracked_paths)
            untracked_rows.append(
                {
                    "root_id": current.root.root_id,
                    "paths": list(git.untracked_paths),
                    "files": [
                        row.to_dict()
                        for row in actual.current_files
                        if row.relative_path in untracked
                    ],
                }
            )
            rows = actual.current_files
        else:
            directory_objects.append(
                {
                    "root_id": current.root.root_id,
                    "device": actual.root_device,
                    "inode": actual.root_inode,
                }
            )
            directory: dict[str, object] = {
                "root": current.root.to_dict(),
                "files": [row.to_dict() for row in actual.files],
                "directories": list(actual.directories),
            }
            directory_roots.append(directory)
            if current.root.source_kind == "generated":
                generated_roots.append(directory)
            rows = actual.files
        current_rows.append(
            {"root": current.root.to_dict(), "files": [row.to_dict() for row in rows]}
        )
    if selected_inputs is None:
        raise ValueError("repository state root must name an actually captured declared Git root")
    state = RepositoryState1.build(
        project_id=domain.project_id,
        root_id=selected,
        registry_generation_id=registry.generation_id,
        registry_sha256=registry.registry_sha256,
        baseline_head=selected_inputs.git.baseline_head,
        head=selected_inputs.git.head,
        head_tree=selected_inputs.git.head_tree,
        baseline_inventory_digest=baseline.baseline_digest,
        index_state_digest=canonical_digest(index_rows),
        worktree_state_digest=canonical_digest(
            {"git": git_roots, "files": current_rows, "directories": directory_roots}
        ),
        untracked_state_digest=canonical_digest(untracked_rows),
        generated_state_digest=canonical_digest(generated_roots),
        configured_roots_digest=domain.domain_digest,
    )
    baseline_source.read()
    snapshot = canonical_digest(
        {
            "configured_sources": inputs.source_snapshot_digest,
            "baseline_reference": reference.to_dict(),
            "baseline_snapshot": baseline_source.snapshot_id,
            "repository_state": state.repository_state_digest,
            "directory_objects": directory_objects,
        }
    )
    return RepositoryStateObservation(state, inputs, baseline, snapshot)
